using System;
using System.Collections.Generic;
using FakeMG.Framework;
using UnityEngine;
using UnityEngine.InputSystem;

namespace FakeMG.InputHints
{
    [CreateAssetMenu(menuName = FakeMGEditorMenus.INPUT_HINTS + "/Input Glyph Set SO")]
    public sealed class InputGlyphSetSO : ScriptableObject
    {
        private const char CONTROL_PATH_SEPARATOR = '/';

        [Header("Devices")]
        [Tooltip("Input System layouts drawn with this set, e.g. 'Keyboard' and 'Mouse', or 'DualShockGamepad'. " +
                 "Layouts based on one of these are included, so 'Gamepad' covers every gamepad.")]
        [SerializeField] private string[] _deviceLayouts = Array.Empty<string>();

        [Space]
        [Header("Diagram")]
        [Tooltip("The device's outlines. With hotspots it becomes a diagram that can highlight one control.")]
        [SerializeField] private Sprite _deviceDiagram;
        [Tooltip("Generated by the glyph set builder: white shapes on transparency, holding the fill behind the whole " +
                 "diagram and each control's highlight.")]
        [SerializeField] private Texture2D _diagramMasks;
        [Tooltip("Where the fill behind the whole diagram sits in the masks texture.")]
        [SerializeField] private Rect _diagramFillUvRect;
        [Tooltip("Each control's highlight. A control without one falls back to its parent, so 'dpad/up' uses 'dpad' when " +
                 "it has no hotspot of its own.")]
        [SerializeField] private List<InputGlyphDiagramHotspot> _diagramHotspots = new();

        [Space]
        [Header("Glyphs")]
        [Tooltip("Control paths relative to the device, e.g. 'buttonSouth', 'leftStick/up', 'scroll/y' or 'f'.")]
        [SerializeField] private List<InputGlyphEntry> _glyphs = new();

        private Dictionary<string, Sprite> _spritesByControlPath;
        private Dictionary<string, InputGlyphDiagramHotspot> _hotspotsByControlPath;

        public Sprite DeviceDiagram => _deviceDiagram;
        public Texture2D DiagramMasks => _diagramMasks;
        public Rect DiagramFillUvRect => _diagramFillUvRect;

        #region Unity Lifecycle

        /// <remarks>Edits in the Inspector must reach the lookups, which are built once.</remarks>
        private void OnValidate()
        {
            _spritesByControlPath = null;
            _hotspotsByControlPath = null;
        }

        #endregion

        #region Public Methods

        public bool Covers(InputDevice device)
        {
            foreach (string layout in _deviceLayouts)
            {
                if (InputSystem.IsFirstLayoutBasedOnSecond(device.layout, layout))
                {
                    return true;
                }
            }

            return false;
        }

        public bool TryGetSprite(string controlPath, out Sprite sprite)
        {
            _spritesByControlPath ??= BuildSpriteLookup();
            return _spritesByControlPath.TryGetValue(controlPath, out sprite);
        }

        public bool TryGetDiagramHotspot(string controlPath, out InputGlyphDiagramHotspot hotspot)
        {
            _hotspotsByControlPath ??= BuildHotspotLookup();
            for (string path = controlPath; !string.IsNullOrEmpty(path); path = ParentOf(path))
            {
                if (_hotspotsByControlPath.TryGetValue(path, out hotspot))
                {
                    return true;
                }
            }

            hotspot = default;
            return false;
        }

        #endregion

        #region Private Methods

        private Dictionary<string, Sprite> BuildSpriteLookup()
        {
            var lookup = new Dictionary<string, Sprite>(StringComparer.OrdinalIgnoreCase);
            foreach (InputGlyphEntry glyph in _glyphs)
            {
                lookup[glyph.ControlPath] = glyph.Sprite;
            }

            return lookup;
        }

        private Dictionary<string, InputGlyphDiagramHotspot> BuildHotspotLookup()
        {
            var lookup = new Dictionary<string, InputGlyphDiagramHotspot>(StringComparer.OrdinalIgnoreCase);
            foreach (InputGlyphDiagramHotspot hotspot in _diagramHotspots)
            {
                lookup[hotspot.ControlPath] = hotspot;
            }

            return lookup;
        }

        private static string ParentOf(string controlPath)
        {
            int separatorIndex = controlPath.LastIndexOf(CONTROL_PATH_SEPARATOR);
            return separatorIndex < 0 ? null : controlPath.Substring(0, separatorIndex);
        }

        #endregion
    }

    [Serializable]
    public struct InputGlyphEntry
    {
        [SerializeField] private string _controlPath;
        [SerializeField] private Sprite _sprite;

        public string ControlPath => _controlPath;
        public Sprite Sprite => _sprite;

        public InputGlyphEntry(string controlPath, Sprite sprite)
        {
            _controlPath = controlPath;
            _sprite = sprite;
        }
    }

    /// <remarks>Normalized to the diagram, with (0, 0) at its bottom-left corner like a UI anchor.</remarks>
    [Serializable]
    public struct InputGlyphDiagramHotspot
    {
        [SerializeField] private string _controlPath;
        [SerializeField] private Vector2 _center01;
        [SerializeField] private Vector2 _size01;
        [SerializeField] private Rect _maskUvRect;

        public string ControlPath => _controlPath;
        public Vector2 AnchorMin01 => _center01 - _size01 * 0.5f;
        public Vector2 AnchorMax01 => _center01 + _size01 * 0.5f;
        public Rect MaskUvRect => _maskUvRect;

        public InputGlyphDiagramHotspot(string controlPath, Vector2 center01, Vector2 size01, Rect maskUvRect)
        {
            _controlPath = controlPath;
            _center01 = center01;
            _size01 = size01;
            _maskUvRect = maskUvRect;
        }
    }
}
